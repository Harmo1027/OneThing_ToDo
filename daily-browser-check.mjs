import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createTodoServer } from "./server.mjs";
import { openDaily } from "./test-browser-helpers.mjs";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.TODO_PLAYWRIGHT || "C:/Users/Harmo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright");
const parent = new URL("./.test-data/", import.meta.url);
await mkdir(parent, { recursive: true });
const dataDirectory = await mkdtemp(path.join(fileURLToPath(parent), "daily-"));
const server = createTodoServer({ dataDirectory });
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: "Asia/Shanghai" });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.clock.install({ time: new Date("2026-11-10T23:59:30+08:00") });
  await page.clock.pauseAt(new Date("2026-11-10T23:59:31+08:00"));
  await page.goto(base);
  await page.locator("#calendar-view").waitFor({ state: "visible" });
  await openDaily(page);
  assert.equal(await page.locator("#daily-empty").isVisible(), true);
  const add = async text => { await page.locator("#daily-input").fill(text); await page.locator("#daily-add-form .primary-button").click(); };
  await add("阅读 20 分钟");
  await add("散步");
  assert.equal(await page.locator(".daily-item").count(), 2);
  await page.locator(".daily-item-title").nth(1).fill("散步 30 分钟");
  await page.locator(".daily-item-title").nth(1).press("Enter");
  await page.locator(".daily-checkbox").first().check();
  assert.equal(await page.locator("#daily-summary").textContent(), "今天已完成 1 / 2");
  await page.reload();
  await openDaily(page);
  assert.equal(await page.locator(".daily-checkbox").first().isChecked(), true);
  assert.equal(await page.locator(".daily-item-title").nth(1).inputValue(), "散步 30 分钟");
  await page.screenshot({ path: path.join(dataDirectory, "daily-desktop.png"), fullPage: true });
  await page.clock.fastForward(60000);
  assert.deepEqual(await page.locator(".daily-item-title").evaluateAll(nodes => nodes.map(node => node.value)), ["阅读 20 分钟", "散步 30 分钟"]);
  assert.equal(await page.locator(".daily-checkbox").first().isChecked(), false);
  assert.equal(await page.locator("#daily-summary").textContent(), "今天已完成 0 / 2");
  await page.locator(".daily-checkbox").nth(1).check();
  await page.locator("#daily-close").click();
  await page.locator("#daily-button").click();
  assert.equal(await page.locator(".daily-checkbox").nth(1).isChecked(), true);
  await page.locator(".daily-item-title").first().fill("  ");
  await page.locator("#daily-input").focus();
  assert.equal(await page.locator(".daily-item-title").first().inputValue(), "阅读 20 分钟");
  await page.locator("#daily-save").click();
  await page.waitForFunction(() => document.querySelector("#daily-save-hint").textContent.includes("已保存到本地"));
  assert.equal(await page.locator("#daily-dialog").isVisible(), true);
  await page.locator("#daily-done").click();
  assert.equal(await page.locator("#daily-dialog").isVisible(), false);
  await page.locator("#save-button").click();
  await page.waitForFunction(() => document.querySelector("#save-status").textContent === "已保存到本地");
  const disk = JSON.parse(await readFile(path.join(dataDirectory, ".todo-workspace.json"), "utf8"));
  assert.equal(disk.state.dailyTasks.length, 2);
  assert.equal(disk.state.dailyTasks[1].completedOn, "2026-11-11");
  const fresh = await browser.newContext({ timezoneId: "Asia/Shanghai" });
  const freshPage = await fresh.newPage();
  await freshPage.clock.install({ time: new Date("2026-11-11T12:00:00+08:00") });
  await freshPage.goto(base);
  await openDaily(freshPage);
  assert.equal(await freshPage.locator(".daily-item-title").nth(1).inputValue(), "散步 30 分钟");
  assert.equal(await freshPage.locator(".daily-checkbox").nth(1).isChecked(), true);
  await freshPage.clock.setSystemTime(new Date("2026-11-12T12:00:00+08:00"));
  await freshPage.reload();
  await openDaily(freshPage);
  assert.deepEqual(await freshPage.locator(".daily-item-title").evaluateAll(nodes => nodes.map(node => node.value)), ["阅读 20 分钟", "散步 30 分钟"]);
  assert.equal(await freshPage.locator(".daily-checkbox:checked").count(), 0);
  for (const width of [768, 375, 320]) {
    await page.setViewportSize({ width, height: 812 });
    await page.locator("#daily-button").click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `页面溢出 ${width}`);
    assert.equal(await page.locator("#daily-dialog").evaluate(el => el.scrollWidth <= el.clientWidth), true, `弹窗溢出 ${width}`);
    if (width === 375) await page.screenshot({ path: path.join(dataDirectory, "daily-mobile.png"), fullPage: true });
    await page.locator("#daily-dialog").press("Escape");
  }
  await page.locator("#daily-button").click();
  while (await page.locator(".daily-delete-button").count()) await page.locator(".daily-delete-button").first().click();
  assert.equal(await page.locator("#daily-empty").isVisible(), true);
  await page.locator("#daily-done").click();
  await page.reload();
  await openDaily(page);
  assert.equal(await page.locator("#daily-empty").isVisible(), true);
  const filePage = await context.newPage();
  await filePage.goto(new URL("./index.html", import.meta.url).href);
  await openDaily(filePage);
  await filePage.locator("#daily-input").fill("HTML 每日任务");
  await filePage.locator("#daily-add-form .primary-button").click();
  await filePage.locator("#daily-save").click();
  assert.match(await filePage.locator("#daily-save-hint").textContent(), /已保存在当前浏览器/);
  await filePage.reload();
  await openDaily(filePage);
  assert.equal(await filePage.locator(".daily-item-title").first().inputValue(), "HTML 每日任务");
  await filePage.locator("#daily-done").click();
  const hash = await filePage.locator(".local-service-link").evaluate(link => { link.addEventListener("click", e => e.preventDefault(), { once: true }); link.click(); return new URL(link.href).hash; });
  const transferPage = await fresh.newPage();
  await transferPage.goto(`${base}/${hash}`);
  await openDaily(transferPage);
  assert.equal(await transferPage.locator(".daily-item-title").count(), 3);
  assert.equal(await transferPage.locator(".daily-item-title").last().inputValue(), "HTML 每日任务");
  assert.deepEqual(errors, []);
  console.log("PASS: 每日清单默认日历落地后按按钮打开、填写一次跨日沿用、弹窗内保存到本地、仅完成勾选每日重置、新浏览器跨日恢复、HTML保存和迁移、重载后手动打开、编辑/删除、320–1440px布局。");
  console.log(`Screenshots: ${dataDirectory}`);
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
}
