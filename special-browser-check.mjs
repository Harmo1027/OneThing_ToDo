import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createTodoServer } from "./server.mjs";
import { openTodo } from "./test-browser-helpers.mjs";

const { chromium } = createRequire(import.meta.url)(process.env.TODO_PLAYWRIGHT || "C:/Users/Harmo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright");
const parent = new URL("./.test-data/", import.meta.url);
await mkdir(parent, { recursive: true });
const dataDirectory = await mkdtemp(path.join(fileURLToPath(parent), "special-"));
const server = createTodoServer({ dataDirectory });
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const main = page.locator("#task-list .task-card");
  const all = () => page.locator('#system-groups [data-group-id="all"]').click();
  const special = field => page.locator(`#system-groups [data-group-id="special:${field}"]`);
  const cache = () => page.evaluate(() => JSON.parse(localStorage.getItem("yijian.workspace.v2")));
  const add = async (title, fields = {}) => {
    await page.locator("#task-heading").fill(title);
    await page.locator("#task-input").fill("完整正文，折叠后仍保留一行滚动预览。".repeat(6));
    for (const [field, value] of Object.entries(fields)) await page.locator(`#task-${field}`).setChecked(value);
    await page.locator(".add-button").click();
    return (await cache()).tasks.find(task => task.title === title).id;
  };
  const card = id => page.locator(`#task-list .task-card[data-id="${id}"]`);
  const edit = async (id, fields) => {
    await card(id).locator(".edit-button").click();
    for (const [field, value] of Object.entries(fields)) await page.locator(`#edit-${field}`).setChecked(value);
    await page.locator("#edit-form .primary-button").click();
  };
  await page.goto(base);
  await openTodo(page);
  assert.equal(await page.locator("#special-cards").count(), 0, "全部待办页不再显示作业与长期事项大卡片");
  assert.equal(await page.locator("#workspace-switcher .workspace-button").count(), 4);
  const rootId = await add("普通任务");
  await card(rootId).locator(".pin-button").click();
  const homeId = await add("作业任务", { homework: true });
  const longId = await add("长期计划", { longTerm: true });
  const bothId = await add("长期作业", { homework: true, longTerm: true });
  assert.equal(await main.count(), 2);
  assert.equal(await page.locator('#system-groups [data-group-id="special:longterm"] .folder-count').textContent(), "2");
  assert.equal(await page.locator('#system-groups [data-group-id="special:homework"] .folder-count').textContent(), "2");
  assert.equal(await page.locator('#system-groups [data-group-id="all"] .folder-count').textContent(), "2");
  await special("longterm").click();
  assert.equal(await page.locator("#page-title").textContent(), "长期事项.");
  assert.equal(await main.count(), 2);
  assert.equal(await page.locator("#task-longTerm").isChecked(), true);
  await card(longId).locator(".pin-button").click();
  assert.equal(await page.locator("#pinned-list .task-card").count(), 1);
  await card(longId).locator(".edit-button").click();
  await page.locator("#edit-priority").selectOption("urgent");
  await page.locator("#edit-form .primary-button").click();
  assert.equal(await page.locator(`#urgent-list [data-id="${longId}"]`).count(), 1);
  const defaultId = await add("本组默认长期任务");
  assert.equal((await cache()).tasks.find(task => task.id === defaultId).groupId, null);
  assert.equal((await cache()).tasks.find(task => task.id === defaultId).longTerm, true);
  await all();
  await card(rootId).dragTo(special("homework"));
  assert.equal((await cache()).tasks.find(task => task.id === rootId).homework, true);
  await edit(rootId, { longTerm: true });
  assert.equal(await card(rootId).count(), 0);
  assert.equal(await page.locator("#pinned-list .task-card").count(), 0);
  await special("homework").click();
  assert.equal(await main.count(), 3);
  await edit(rootId, { longTerm: false });
  assert.equal(await page.locator(`#pinned-list [data-id="${rootId}"]`).count(), 1);
  await page.locator("#add-group-button").click();
  await page.locator("#group-name").fill("学习");
  await page.locator("#group-form .primary-button").click();
  const groupId = await page.locator("#custom-groups .active").getAttribute("data-group-id");
  const groupedId = await add("学习中的长期作业", { homework: true, longTerm: true });
  await card(groupedId).locator(".pin-button").click();
  await card(groupedId).locator(".fold-button").click();
  assert.equal(await card(groupedId).locator(".collapsed-preview").count(), 1);
  await page.locator("#save-button").click();
  await page.waitForFunction(() => document.querySelector("#save-status").textContent === "已保存到本地");
  const before = (await readdir(dataDirectory, { recursive: true })).sort();
  assert.deepEqual(before.filter(file => !file.endsWith(".json")), ["学习"]);
  const groupedFile = path.join(dataDirectory, "学习", `${groupedId}.todo.json`);
  const savedTask = JSON.parse(await readFile(groupedFile, "utf8")).task;
  assert.equal(savedTask.homework, true);
  assert.equal(savedTask.longTerm, true);
  assert.equal(savedTask.groupId, groupId);
  await edit(groupedId, { homework: false, longTerm: false });
  await page.locator("#save-button").click();
  await page.waitForFunction(() => document.querySelector("#save-status").textContent === "已保存到本地");
  assert.deepEqual((await readdir(dataDirectory, { recursive: true })).sort(), before);
  await all();
  assert.equal(await main.count(), 3);
  await edit(groupedId, { homework: true, longTerm: true });
  await page.locator("#save-button").click();
  await page.waitForFunction(() => document.querySelector("#save-status").textContent === "已保存到本地");
  await context.clearCookies();
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await openTodo(page);
  assert.equal(await main.count(), 2);
  assert.equal(await page.locator("#pinned-list .task-card").count(), 1);
  await special("longterm").click();
  assert.equal(await main.count(), 4);
  assert.equal(await card(bothId).count(), 1);
  assert.equal(await card(groupedId).count(), 1);
  await card(longId).locator(".move-select").selectOption(groupId);
  assert.equal((await cache()).tasks.find(task => task.id === longId).longTerm, true);
  await page.locator(`#custom-groups [data-group-id="${groupId}"]`).click();
  assert.equal(await main.count(), 2);
  await all();
  await page.screenshot({ path: path.join(dataDirectory, "special-desktop.png"), fullPage: true });
  for (const width of [768, 375, 320]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `no page overflow at ${width}`);
    await special("homework").click();
    await card(homeId).locator(".edit-button").click();
    assert.equal(await page.locator("#edit-longTerm").isVisible(), true);
    assert.equal(await page.locator("#edit-dialog").evaluate(node => node.scrollWidth <= node.clientWidth), true);
    await page.locator("#cancel-edit").click();
    await all();
  }
  await page.screenshot({ path: path.join(dataDirectory, "special-mobile.png"), fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: "special groups passed", dataDirectory, tasks: (await cache()).tasks.length }));
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
}
